-- ============================================================================
-- 005 — like_seen にタイムスタンプを持たせ、配信中の定期プルーンを可能にする。
--
-- like_seen は「(再)接続時に TikTok が再送するバックログの二重計上防止」が目的で、
-- 保護すべき期間は数分 + SESSION_RESUME_GAP_MS(10分)まで。それなのに行は
-- セッション終了まで消えず、長時間耐久配信ではいいね1件 = 1行で数百万行まで
-- 育ち、INSERT OR IGNORE のコストが時間とともに増え続けていた。
-- ts_ms を足して「30分より古い行は捨てる」を配信中に回せるようにする。
-- ============================================================================

ALTER TABLE like_seen ADD COLUMN ts_ms INTEGER NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS like_seen_ts ON like_seen(ts_ms);
